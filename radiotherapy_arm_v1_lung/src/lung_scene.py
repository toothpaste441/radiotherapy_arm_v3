"""Illustrative table/patient with a lung lesion and visible external chest marker.

Reuses the already validated V3 scene primitives and translates the mannequin
so the synthetic target is in the upper torso rather than in the head.
"""
from __future__ import annotations
from dataclasses import dataclass, replace
from pathlib import Path
import xml.etree.ElementTree as ET
import numpy as np
from src.brain_scene import create_brain_scene
from src.path_planning import SphereObstacle
from src.robust_collision import BoxObstacle


def _xyz(x):
    return ' '.join(f'{float(v):.8f}' for v in x)

@dataclass(frozen=True)
class LungScene:
    xml_path: Path
    tumour_anchor: np.ndarray
    head_center: np.ndarray
    torso_center: np.ndarray
    chest_marker_origin: np.ndarray
    surface_origin: np.ndarray
    obstacles: tuple
    beam_names: tuple[str,...]
    arm_spread_m: tuple[float,float] = (0.0, 0.0)
    base_offset_world_m: tuple[float,float,float] = (0.0, 0.0, 0.0)


def create_lung_scene(source_xml:Path, output_xml:Path, reference_tool, reference_axis,
                      arm_spread_m=(0.0, 0.0)):
    """Place the mannequin around the lung target, with adjustable arm clearance.

    arm_spread_m is (left_outward, right_outward) in metres. Changes are
    applied to BOTH the visible arm capsules and the matching collision boxes.
    """
    spreads=np.asarray(arm_spread_m,dtype=float)
    if spreads.shape!=(2,) or not np.all(np.isfinite(spreads)) or np.any(spreads<0) or np.any(spreads>0.25):
        raise ValueError('Arm spread must be two finite values between 0 and 0.25 m')

    output_xml=Path(output_xml)
    first=create_brain_scene(source_xml,output_xml,reference_tool,reference_axis)
    # The old head-centred target is shifted anatomically into the upper torso.
    shift=np.array([0.,-0.53,0.085])
    root=ET.parse(output_xml)
    world=root.getroot().find('worldbody')
    for geom in world.findall('geom'):
        name=geom.get('name','')
        if name.startswith('patient_') or name.startswith('table_'):
            geom.set('pos',_xyz(np.fromstring(geom.get('pos'),sep=' ')+shift))
            if name=='patient_torso':
                geom.set('size',_xyz([0.17,0.28,0.10]))
                geom.set('rgba','0.34 0.61 0.73 0.85')
            if name in ('patient_arm_0','patient_arm_1'):
                side=0 if name.endswith('_0') else 1
                direction=-1.0 if side==0 else 1.0
                p=np.fromstring(geom.get('pos'),sep=' ')
                p[0]+=direction*spreads[side]
                geom.set('pos',_xyz(p))
    # A translucent moving surface panel provides an obvious visual cue for
    # respiratory chest rise; it is illustrative and excluded from collisions.
    patch=ET.SubElement(world,'body',name='breathing_chest_surface',mocap='true',
                        pos=_xyz(first.brain_target+[0.,0.,0.105]))
    ET.SubElement(patch,'geom',name='breathing_surface_geom',type='box',
                  size=_xyz([0.14,0.19,0.012]),rgba='0.15 0.78 0.89 0.28',
                  contype='0',conaffinity='0')
    body=ET.SubElement(world,'body',name='chest_observation_marker',mocap='true',
                       pos=_xyz(first.brain_target+[0.,0.,0.17]))
    ET.SubElement(body,'geom',name='observed_chest_dot',type='sphere',size='0.012',
                  rgba='0.12 0.95 0.38 1',contype='0',conaffinity='0')
    # Decorative fixed eye-to-hand camera mounted beside the patient's chest.
    # Pixel observations are generated by the independent pinhole camera model
    # in vision_servo.py, NOT by sampling this rendered visual object.
    camera_pos=first.brain_target+np.array([0.,0.,0.17])+[0.,-1.2,0.2]
    ET.SubElement(world,'geom',name='fixed_chest_camera_housing',type='box',
                  pos=_xyz(camera_pos),size=_xyz([0.065,0.045,0.045]),
                  rgba='0.22 0.25 0.3 1',contype='0',conaffinity='0')
    ET.SubElement(world,'geom',name='fixed_chest_camera_lens',type='sphere',
                  pos=_xyz(camera_pos+[0,0.045,0]),size='0.023',
                  rgba='0.1 0.45 0.85 1',contype='0',conaffinity='0')
    # Replace the brain lesion label and move its mocap position at runtime.
    tumour_geom=root.getroot().find('.//geom[@name="tumor_marker"]')
    if tumour_geom is not None:
        tumour_geom.set('size','0.009')
        tumour_geom.set('rgba','0.95 0.1 0.12 1')
    root.write(output_xml,encoding='unicode',xml_declaration=True)
    obstacles=[]
    for obs in first.obstacles:
        if isinstance(obs,SphereObstacle):
            obstacles.append(SphereObstacle(obs.center+shift,obs.radius,obs.name))
        elif isinstance(obs,BoxObstacle):
            half=obs.half_extents.copy()
            if obs.name=='torso_box':half=np.array([0.17,0.28,0.10])
            center=obs.center+shift
            if obs.name in ('left_arm_box','right_arm_box'):
                side=0 if obs.name=='left_arm_box' else 1
                center=center.copy()
                center[0]+=(-1.0 if side==0 else 1.0)*spreads[side]
            obstacles.append(BoxObstacle(center,half,obs.name))
    target=first.brain_target.copy()
    return LungScene(output_xml,target,first.head_center+shift,
                     target-0.01*np.asarray(reference_axis),
                     target+np.array([0.,0.,0.17]),target+np.array([0.,0.,0.105]),
                     tuple(obstacles),first.beam_names,tuple(map(float,spreads)))


def relocate_robot_base(scene: LungScene, translation_world_m) -> LungScene:
    """Relocate only the fixed robot root in an already generated patient scene.

    The patient, table, tumour, and collision proxies remain in the original
    world coordinates. Translate the *root body* so the tool kinematics are
    rebuilt from the new MuJoCo model, not offset after the fact.

    Always call on a freshly created scene, since this translation is additive.
    """
    delta = np.asarray(translation_world_m, dtype=float)
    if delta.shape != (3,) or not np.all(np.isfinite(delta)) or abs(delta[2]) > 1e-12:
        raise ValueError('Base translation must be finite 3D, with no vertical shift')
    tree = ET.parse(scene.xml_path)
    robot = tree.getroot().find("./worldbody/body[@name='robot_base']")
    if robot is None:
        raise ValueError('robot_base body missing from the MuJoCo scene')
    original = np.fromstring(robot.get('pos', '0 0 0'), sep=' ')
    if original.shape != (3,):
        raise ValueError('Invalid robot_base position')
    robot.set('pos', _xyz(original + delta))
    tree.write(scene.xml_path, encoding='unicode', xml_declaration=True)
    return replace(scene, base_offset_world_m=tuple(map(float, delta)))
